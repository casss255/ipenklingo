/* Mandarin course, taught in Indonesian.
   Word: [hanzi, indonesian, pinyin]
   Sentence: zs('字/pīnyīn 字/pīnyīn ，/ ...', indonesian, ...acceptedVariants)
   A token is hanzi/pinyin, punctuation has an empty pinyin, and "_" inside pinyin stands for a space.
   Keep the first six lesson ids and their order: saved progress is keyed by id. */
const zs = (str, id, ...alt) => {
  const tk = str.split(' ').map(t => { const i = t.indexOf('/'); return [t.slice(0, i), t.slice(i + 1).replace(/_/g, ' ')]; });
  return alt.length ? { tk, id, alt } : { tk, id };
};

